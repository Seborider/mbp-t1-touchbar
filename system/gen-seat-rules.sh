#!/bin/bash
# Regenerate /etc/udev/rules.d/71-seat.rules from the CURRENT stock systemd
# file, with two Touch Bar exclusions added.
#
# Why this exists
# ---------------
# systemd's 71-seat.rules tags every DRM card as a seat master:
#
#   SUBSYSTEM=="drm", KERNEL=="card[0-9]*", TAG+="seat", TAG+="master-of-seat"
#
# so the Touch Bar joins seat0, the compositor takes DRM master on it at
# startup and never releases it, and nothing else can modeset the panel.
#
# udev cannot remove a tag - TAG-= is a no-op on udev 261 - so the device has
# to skip the whole file with GOTO="seat_end" instead. Upstream tiny-dfr's
# 99-touchbar-seat.rules relies on TAG-= and does not work here.
#
# Do NOT set ENV{ID_SEAT} on the DRM card: logind synthesises a seat from it,
# the display manager builds a D-Bus object path from the name, the hyphen is
# illegal in D-Bus paths, and SDDM crash-loops into a black screen.
#
# Because this file SHADOWS a systemd-owned file by name, it must be
# regenerated after every systemd upgrade or it will pin an outdated copy.
# The pacman hook in ../system/pacman-hooks/ does that automatically.
set -u
STOCK=/usr/lib/udev/rules.d/71-seat.rules
OVERRIDE=/etc/udev/rules.d/71-seat.rules

[ -r "$STOCK" ] || { echo "gen-seat-rules: $STOCK not readable"; exit 1; }

python3 - "$STOCK" "$OVERRIDE" <<'PYEOF'
import sys
stock, out = sys.argv[1], sys.argv[2]
s = open(stock).read()
anchor = 'ACTION=="remove", GOTO="seat_end"'
if anchor not in s:
    sys.exit("gen-seat-rules: anchor line not found in stock 71-seat.rules")

exclusion = '''
# --- Apple T1/T2 Touch Bar ------------------------------------------------
# The DFR display must not become a seat device. As a seat master logind
# synthesises a seat for it and the display manager tries to run a greeter on
# the Touch Bar; while it belongs to seat0 the compositor takes DRM master on
# it and the Touch Bar renderer cannot drive the panel. udev cannot remove a
# tag, so the device skips this file entirely.
SUBSYSTEM=="drm", KERNEL=="card[0-9]*", SUBSYSTEMS=="usb", ATTRS{idVendor}=="05ac", ATTRS{idProduct}=="8600", GOTO="seat_end"
SUBSYSTEM=="drm", KERNEL=="card[0-9]*", SUBSYSTEMS=="usb", ATTRS{idVendor}=="05ac", ATTRS{idProduct}=="8302", GOTO="seat_end"

# The Touch Bar digitizer is read by tiny-dfr through libinput's
# "seat-touchbar" udev seat. libinput matches on the ID_SEAT property while
# logind creates seats from the "seat" tag, so setting the property and
# skipping the tagging keeps it away from both seat0 and the display manager.
SUBSYSTEM=="input", ATTRS{name}=="Apple Inc. iBridge Touchpad", ENV{ID_SEAT}="seat-touchbar", GOTO="seat_end"
SUBSYSTEM=="input", ATTRS{name}=="Apple Inc. Touch Bar Display Touchpad", ENV{ID_SEAT}="seat-touchbar", GOTO="seat_end"
SUBSYSTEM=="input", ATTRS{name}=="Apple Inc. Apple T1 Controller Touchpad", ENV{ID_SEAT}="seat-touchbar", GOTO="seat_end"
# --------------------------------------------------------------------------
'''

header = ("# Generated by mbp-t1-touchbar/system/gen-seat-rules.sh - do not edit.\n"
          "# Local override of systemd's 71-seat.rules with Touch Bar exclusions.\n"
          "# REGENERATE AFTER EVERY SYSTEMD UPGRADE.\n")
open(out, 'w').write(header + s.replace(anchor, anchor + '\n' + exclusion, 1))
print("gen-seat-rules: wrote " + out)
PYEOF

udevadm control --reload-rules

# Safety check: the real GPU must keep its seat tags, or the desktop will not
# come up on the next boot. Revert rather than risk it.
I915=""
for c in /sys/class/drm/card[0-9]; do
    drv=$(readlink -f "$c/device/driver" 2>/dev/null | xargs -r basename)
    case "$drv" in i915|amdgpu|nouveau|nvidia) I915=$c ;; esac
done
if [ -n "$I915" ] && ! udevadm test "$I915" 2>&1 | grep -q 'master-of-seat'; then
    echo "gen-seat-rules: !! $(basename "$I915") would lose master-of-seat - REVERTING"
    rm -f "$OVERRIDE"
    udevadm control --reload-rules
    exit 1
fi
echo "gen-seat-rules: OK ($(basename "${I915:-no primary GPU found}") keeps master-of-seat)"
